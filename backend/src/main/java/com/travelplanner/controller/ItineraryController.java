package com.travelplanner.controller;

import com.travelplanner.common.dto.ApiResponse;
import com.travelplanner.common.security.UserPrincipal;
import com.travelplanner.dto.itinerary.*;
import com.travelplanner.service.ItineraryService;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/trips/{tripId}/itinerary")
public class ItineraryController {

    private final ItineraryService itineraryService;

    public ItineraryController(ItineraryService itineraryService) {
        this.itineraryService = itineraryService;
    }

    @GetMapping
    public ResponseEntity<ApiResponse<ItineraryResponse>> getItinerary(
            @AuthenticationPrincipal UserPrincipal principal,
            @PathVariable String tripId) {
        String userId = principal != null ? principal.getId() : null;
        ItineraryResponse response = itineraryService.getItineraryByTripId(tripId, userId);
        return ResponseEntity.ok(ApiResponse.ok(response));
    }

    @PostMapping("/days/{dayId}/activities")
    public ResponseEntity<ApiResponse<ItineraryActivityDto>> addActivity(
            @AuthenticationPrincipal UserPrincipal principal,
            @PathVariable String tripId,
            @PathVariable String dayId,
            @Valid @RequestBody ActivityCreateRequest request) {
        ItineraryActivityDto dto = itineraryService.addActivity(dayId, request, principal.getId());
        return ResponseEntity.status(HttpStatus.CREATED).body(ApiResponse.ok("Activity added", dto));
    }

    @PutMapping("/activities/{activityId}")
    public ResponseEntity<ApiResponse<ItineraryActivityDto>> updateActivity(
            @AuthenticationPrincipal UserPrincipal principal,
            @PathVariable String tripId,
            @PathVariable String activityId,
            @RequestBody ActivityUpdateRequest request) {
        ItineraryActivityDto dto = itineraryService.updateActivity(activityId, request, principal.getId());
        return ResponseEntity.ok(ApiResponse.ok("Activity updated", dto));
    }

    @DeleteMapping("/activities/{activityId}")
    public ResponseEntity<ApiResponse<Void>> deleteActivity(
            @AuthenticationPrincipal UserPrincipal principal,
            @PathVariable String tripId,
            @PathVariable String activityId) {
        itineraryService.deleteActivity(activityId, principal.getId());
        return ResponseEntity.ok(ApiResponse.ok("Activity deleted", null));
    }

    @PostMapping("/reorder")
    public ResponseEntity<ApiResponse<Void>> reorderActivities(
            @AuthenticationPrincipal UserPrincipal principal,
            @PathVariable String tripId,
            @RequestBody ReorderActivitiesRequest request) {
        itineraryService.reorderActivities(request, principal.getId());
        return ResponseEntity.ok(ApiResponse.ok("Activities reordered successfully", null));
    }

    @PostMapping("/days/{dayId}/regenerate")
    public ResponseEntity<ApiResponse<ItineraryDayDto>> regenerateDay(
            @AuthenticationPrincipal UserPrincipal principal,
            @PathVariable String tripId,
            @PathVariable String dayId) {
        ItineraryDayDto dto = itineraryService.regenerateDay(dayId, principal.getId());
        return ResponseEntity.ok(ApiResponse.ok("Day schedule regenerated by Itinerary Agent", dto));
    }
}
